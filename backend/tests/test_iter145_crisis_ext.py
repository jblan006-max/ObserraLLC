class TestSitrepConsole:
    def test_preview_and_note_persist(self, sess):
        r = sess.post(f"{BASE_URL}/api/crisis/cases",
                      json={"title": "TEST_ITER145 sitrep console",
                            "severity": "Low", "summary": "TEST_ITER145"}, timeout=15)
        assert r.status_code == 200
        ref = r.json()["ref"]
        try:
            p0 = sess.get(f"{BASE_URL}/api/crisis/cases/{ref}/sitrep/preview", timeout=15)
            assert p0.status_code == 200
            b0 = p0.json()
            for k in ("title", "text", "note", "cadence_hours"):
                assert k in b0, f"missing key {k} in preview"
            assert b0["note"] == ""

            # patch a note
            note = "TEST_ITER145 · exec team standby at 15:00 UTC"
            rp = sess.patch(f"{BASE_URL}/api/crisis/cases/{ref}",
                            json={"sitrep_note": note}, timeout=15)
            assert rp.status_code == 200

            p1 = sess.get(f"{BASE_URL}/api/crisis/cases/{ref}/sitrep/preview", timeout=15).json()
            assert p1["note"] == note
            assert note in p1["text"], "note should appear in composed preview text"
        finally:
            _delete_case_via_mongo(ref)

    def test_send_now_posts_and_writes_timeline(self, sess):
        """Monkey-patch self_scan._post_chat_alert BEFORE calling the endpoint.
        The endpoint imports the symbol inside the function via
        `from self_scan import _post_chat_alert`, so patching the module attr works.
        """
        # Load backend .env before import
        for line in open("/app/backend/.env"):
            if "=" in line and not line.strip().startswith("#"):
                k, _, v = line.strip().partition("=")
                os.environ.setdefault(k, v.strip().strip('"').strip("'"))
        sys.path.insert(0, "/app/backend")
        import self_scan as _ss
        original = _ss._post_chat_alert
        calls = {"n": 0}

        async def _no_op(oid, title, text):
            calls["n"] += 1
            return None
        _ss._post_chat_alert = _no_op
        try:
            r = sess.post(f"{BASE_URL}/api/crisis/cases",
                          json={"title": "TEST_ITER145 sitrep send-now",
                                "severity": "Low", "summary": "TEST_ITER145"}, timeout=15)
            ref = r.json()["ref"]
            try:
                sess.patch(f"{BASE_URL}/api/crisis/cases/{ref}",
                           json={"sitrep_note": "TEST_ITER145 note"}, timeout=15)
                rs = sess.post(f"{BASE_URL}/api/crisis/cases/{ref}/sitrep/send-now", timeout=20)
                assert rs.status_code == 200, f"{rs.status_code} {rs.text[:200]}"
                body = rs.json()
                assert "posted" in body
                assert "teams" in body and "slack" in body

                # timeline event 'Manual SITREP sent to leadership chat'
                time.sleep(0.5)
                tl = sess.get(f"{BASE_URL}/api/crisis/cases/{ref}/timeline", timeout=15).json()
                events = tl.get("events") if isinstance(tl, dict) else tl
                manual = [e for e in (events or [])
                          if "Manual SITREP sent to leadership chat" in (e.get("title") or "")]
                assert len(manual) >= 1, "expected Manual SITREP timeline event"
            finally:
                _delete_case_via_mongo(ref)
        finally:
            _ss._post_chat_alert = original


