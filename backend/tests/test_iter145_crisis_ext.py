# FEATURE 1 — Connector Test Ping
# ==========================
class TestConnectorTestPing:
    def test_ping_crowdstrike_updates_health_no_case(self, sess):
        # Snapshot case refs + baseline health
        def _refs():
            body = sess.get(f"{BASE_URL}/api/crisis/cases", timeout=15).json()
            arr = body.get("cases", body) if isinstance(body, dict) else body
            return {c.get("ref") for c in (arr or []) if c.get("ref")}
        before = _refs()
        h0 = sess.get(f"{BASE_URL}/api/crisis/connectors/native", timeout=15).json()
        base = next((c for c in h0["connectors"] if c["vendor"] == "crowdstrike"), {})
        base_count = int(base.get("count") or 0)

        r = sess.post(f"{BASE_URL}/api/crisis/connectors/crowdstrike/test", timeout=15)
        assert r.status_code == 200, f"{r.status_code} {r.text[:200]}"
        body = r.json()
        assert body.get("ok") is True
        assert body.get("vendor") == "crowdstrike"
        assert "mapped" in body and isinstance(body["mapped"], dict)

        # health updated
        h1 = sess.get(f"{BASE_URL}/api/crisis/connectors/native", timeout=15).json()
        after = next((c for c in h1["connectors"] if c["vendor"] == "crowdstrike"), {})
        assert after.get("last_received"), "last_received not set after test ping"
        assert int(after.get("count") or 0) >= base_count + 1

        # no new crisis case attributable to the test ping.
        # (Filter out any TEST_ITER145 cases that other parallel tests may create.)
        after_refs = _refs()
        new_refs = after_refs - before
        if new_refs:
            # Anything newly created must not have been generated by the test ping.
            for ref in new_refs:
                c = sess.get(f"{BASE_URL}/api/crisis/cases/{ref}", timeout=10).json()
                title = ((c.get("case") or c).get("title") or "")
                assert "connection test" not in title.lower() and "obserra connection" not in title.lower(), (
                    f"connector test appears to have created a case: {ref} / {title}")

    def test_ping_all_vendors_ok(self, sess):
        for v in ("splunk", "sentinel", "servicenow", "generic"):
            r = sess.post(f"{BASE_URL}/api/crisis/connectors/{v}/test", timeout=15)
            assert r.status_code == 200, f"{v} -> {r.status_code}"
            assert r.json().get("ok") is True


